#!/usr/bin/env python3
"""Generate MODLIST.md from pack/modrinth.index.json.

Usage: python3 tools/modlist.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
idx = json.loads((root / "pack" / "modrinth.index.json").read_text(encoding="utf-8"))

JEI_FAMILY = ("jei-", "mezz_config", "sophisticated_jei_index")


def side(f):
    c, s = f["env"]["client"], f["env"]["server"]
    name = f["path"].split("/", 1)[1]
    if s == "unsupported":
        return "Client only" + (" (optional)" if c == "optional" else "")
    if name.startswith(JEI_FAMILY):
        return "Client only"
    if c == "optional":
        return "Server + optional on client"
    return "Client + Server"


rows = {"mods": [], "resourcepacks": [], "other": []}
for f in idx["files"]:
    folder, name = f["path"].split("/", 1)
    url = f["downloads"][0]
    pid = url.split("/")[4] if "cdn.modrinth.com" in url else None
    link = f"[{name}](https://modrinth.com/project/{pid})" if pid else name
    rows.get(folder, rows["other"]).append((name.lower(), link, side(f)))

out = [
    f"# Mod list - NEP Create Modpack {idx['versionId']}",
    "",
    f"Minecraft {idx['dependencies']['minecraft']} - NeoForge {idx['dependencies']['neoforge']}",
    "",
    "Generated by `tools/modlist.py` from `pack/modrinth.index.json`. Do not edit by hand.",
    "",
]
for title, key in (("Mods", "mods"), ("Resource packs", "resourcepacks"), ("Other", "other")):
    if not rows[key]:
        continue
    out += [f"## {title} ({len(rows[key])})", "", "| File | Side |", "|---|---|"]
    out += [f"| {link} | {s} |" for _, link, s in sorted(rows[key])]
    out.append("")

(root / "MODLIST.md").write_text("\n".join(out), encoding="utf-8")
print(f"MODLIST.md: {sum(len(v) for v in rows.values())} entries")
